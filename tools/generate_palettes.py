"""Generate byte-stable BGR constants from the two authoritative XML presets."""
from pathlib import Path
import argparse
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]


def content():
    lines = ['#pragma once', '// Generated by tools/generate_palettes.py from styles/ForeLexer-*.xml.',
             '#include <array>', 'namespace fore {']
    for name in ('Light', 'Dark'):
        nodes = ET.parse(ROOT/f'styles/ForeLexer-{name}.xml').findall('LexerStyles/LexerType/WordsStyle')
        nodes.sort(key=lambda node: int(node.get('styleID')))
        assert [int(node.get('styleID')) for node in nodes] == list(range(11))
        colors = [int.from_bytes(bytes.fromhex(node.get('fgColor')), 'little') for node in nodes]
        values = ', '.join(f'0x{value:06X}UL' for value in colors)
        lines.append(f'inline constexpr std::array<unsigned long, 11> {name}Colors {{{values}}};')
    return ('\n'.join(lines+['}', ''])).encode('utf-8')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT/'src/ForePaletteData.h'
    expected = content()
    if args.check:
        assert path.read_bytes() == expected, 'Regenerate ForePaletteData.h after changing a preset'
        print('PALETTES: compiled constants match both XML presets byte-for-byte.')
    else:
        path.write_bytes(expected)


if __name__ == '__main__':
    main()
